// src/components/ReportView.jsx
import ReactMarkdown from "react-markdown";
import SourceText from "./SourceText";

// The backend builds a Sources section at the end of the report.
// We show sources in their own panel, so remove it from the body.
function stripSourcesSection(markdown) {
  return (markdown || "").split(/\n#+\s*Sources\b/i)[0].trimEnd();
}

const markdownComponents = {
  h1: ({ children }) => (
    <h1 className="mb-3 mt-8 text-2xl font-bold text-slate-800">{children}</h1>
  ),
  h2: ({ children }) => (
    <h2 className="mb-3 mt-8 text-xl font-bold text-slate-800">{children}</h2>
  ),
  h3: ({ children }) => (
    <h3 className="mb-2 mt-6 text-lg font-semibold text-slate-800">{children}</h3>
  ),
  h4: ({ children }) => (
    <h4 className="mb-2 mt-5 text-base font-semibold text-slate-800">{children}</h4>
  ),
  p: ({ children }) => <p className="mb-4 leading-7 text-slate-700">{children}</p>,
  ul: ({ children }) => (
    <ul className="mb-4 list-disc space-y-2 pl-6 text-slate-700">{children}</ul>
  ),
  ol: ({ children }) => (
    <ol className="mb-4 list-decimal space-y-2 pl-6 text-slate-700">{children}</ol>
  ),
  li: ({ children }) => <li className="leading-7">{children}</li>,
  strong: ({ children }) => (
    <strong className="font-semibold text-slate-900">{children}</strong>
  ),
  a: ({ href, children }) => (
    <a href={href} target="_blank" rel="noreferrer" className="text-blue-600 hover:underline">
      {children}
    </a>
  ),
};

function scoreStyle(score) {
  if (score === null || score === undefined) return "bg-slate-100 text-slate-600";
  if (score >= 8) return "bg-green-100 text-green-700";
  if (score >= 5) return "bg-amber-100 text-amber-700";
  return "bg-red-100 text-red-700";
}

export default function ReportView({ result }) {
  const score = result.review?.score;
  const finished = result.finished_at
    ? new Date(result.finished_at).toLocaleString()
    : "";

  return (
    <div>
      <div className="mb-6 flex flex-wrap items-center gap-3 text-sm text-slate-500">
        <span>
          Generated by {result.llm_provider} / {result.llm_model}
        </span>
        {finished && <span>· Finished {finished}</span>}
      </div>

      <article>
        <ReactMarkdown components={markdownComponents}>
          {stripSourcesSection(result.report)}
        </ReactMarkdown>
      </article>

      <section className="mt-10 border-t border-slate-200 pt-6">
        <h2 className="mb-3 text-lg font-semibold text-slate-800">Sources</h2>
        {result.sources.length === 0 ? (
          <p className="text-sm text-slate-500">No usable sources were found.</p>
        ) : (
          <ol className="list-decimal space-y-2 pl-6">
            {result.sources.map((url) => (
              <li key={url}>
                <a
                  href={url}
                  target="_blank"
                  rel="noreferrer"
                  className="break-all text-sm text-blue-600 hover:underline"
                >
                  {url}
                </a>
              </li>
            ))}
          </ol>
        )}
      </section>

      <section className="mt-10 border-t border-slate-200 pt-6">
        <div className="mb-3 flex items-center gap-3">
          <h2 className="text-lg font-semibold text-slate-800">Review</h2>
          <span
            className={`rounded-full px-3 py-1 text-sm font-semibold ${scoreStyle(score)}`}
          >
            {score !== null && score !== undefined ? `${score}/10` : "Not scored"}
          </span>
        </div>
        <p className="whitespace-pre-line text-sm leading-6 text-slate-700">
          {result.review?.text}
        </p>
      </section>

      <SourceText scraped={result.scraped} />
    </div>
  );
}