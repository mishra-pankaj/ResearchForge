// src/utils/pdf.js
import { jsPDF } from "jspdf";

const MARGIN = 20;
const PAGE_HEIGHT_LIMIT = 280;
const LINE_HEIGHT = 6;

// Make a topic safe to use as a file name.
function safeFileName(topic) {
  const cleaned = topic
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, "")
    .trim()
    .replace(/\s+/g, "-")
    .slice(0, 80);
  return `${cleaned || "research-report"}.pdf`;
}

// Remove Markdown markers and keep the visible text.
function plainText(line) {
  return line
    .replace(/\*\*(.+?)\*\*/g, "$1")
    .replace(/\*(.+?)\*/g, "$1")
    .replace(/`(.+?)`/g, "$1")
    .replace(/\[(.+?)\]\((.+?)\)/g, "$1")
    .trim();
}

// Break one paragraph into lines that fit the page width.
function wrap(doc, text, width) {
  return doc.splitTextToSize(text, width);
}

export function buildReportPdf(result) {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const width = doc.internal.pageSize.getWidth() - MARGIN * 2;
  let y = MARGIN;

  // Start a new page when the current one is full.
  function ensureSpace(lines = 1) {
    if (y + lines * LINE_HEIGHT > PAGE_HEIGHT_LIMIT) {
      doc.addPage();
      y = MARGIN;
    }
  }

  function writeBlock(text, { size = 11, bold = false, indent = 0, gap = 0 } = {}) {
    doc.setFont("helvetica", bold ? "bold" : "normal");
    doc.setFontSize(size);
    const lines = wrap(doc, text, width - indent);
    for (const line of lines) {
      ensureSpace();
      doc.text(line, MARGIN + indent, y);
      y += LINE_HEIGHT;
    }
    y += gap;
  }

  // Title and metadata
  writeBlock(result.topic || "Research report", { size: 18, bold: true, gap: 2 });
  const finished = result.finished_at
    ? new Date(result.finished_at).toLocaleString()
    : "";
  writeBlock(
    `Generated by ${result.llm_provider} / ${result.llm_model}${finished ? ` · Finished ${finished}` : ""}`,
    { size: 9, gap: 4 }
  );

  // Report body, without its Sources section
  const body = (result.report || "").split(/\n#+\s*Sources\b/i)[0].trimEnd();

  for (const raw of body.split("\n")) {
    const line = raw.trim();
    if (!line) {
      y += 2;
      continue;
    }

    const heading = line.match(/^(#{1,4})\s+(.*)$/);
    if (heading) {
      const level = heading[1].length;
      writeBlock(plainText(heading[2]), {
        size: level <= 2 ? 14 : 12,
        bold: true,
        gap: 1,
      });
      continue;
    }

    const bullet = line.match(/^[-*•]\s+(.*)$/);
    if (bullet) {
      writeBlock(`- ${plainText(bullet[1])}`, { indent: 4 });
      continue;
    }

    const numbered = line.match(/^(\d+)\.\s+(.*)$/);
    if (numbered) {
      writeBlock(`${numbered[1]}. ${plainText(numbered[2])}`, { indent: 4 });
      continue;
    }

    writeBlock(plainText(line), { gap: 1 });
  }

  // Sources, printed in full, numbered
  y += 4;
  writeBlock("Sources", { size: 14, bold: true, gap: 1 });
  const sources = result.sources || [];
  if (sources.length === 0) {
    writeBlock("No usable sources were found.");
  } else {
    sources.forEach((url, index) => {
      writeBlock(`${index + 1}. ${url}`, { indent: 4 });
    });
  }

  // Page numbers at the bottom of each page
  const pageCount = doc.getNumberOfPages();
  for (let page = 1; page <= pageCount; page += 1) {
    doc.setPage(page);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.text(`${page} / ${pageCount}`, doc.internal.pageSize.getWidth() / 2, 290, {
      align: "center",
    });
  }

  return {
    blob: doc.output("blob"),
    fileName: safeFileName(result.topic || "research-report"),
  };
}